export function entryText(hero: Hero): string {
  if (hero.faction === '무소속') {
    if (hero.entry.includes('은거')) return '열세 살이 되던 해, 산중의 노인이 당신을 거두었다. 노인은 이름도 문파도 말해 주지 않았다.';
    if (hero.entry.includes('사마')) return '열세 살이 되던 해, 낯선 자들이 당신을 데려갔다. 그곳에서 배운 무공은 피 냄새가 났다.';
    return '열세 살이 되던 해, 당신은 헌 책방 구석에서 표지가 떨어져 나간 비급 한 권을 주웠다.';
  }
  return `열세 살이 되던 해, 당신은 ${hero.faction}의 문을 넘었다. (${hero.entry})`;
}
